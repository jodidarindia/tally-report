def _lakhs(v: float) -> str:
    """Format as Indian lakhs — matches bank CMA layout (Rs. in Lacs)."""
    if v is None:
        return "-"
    try:
        v = float(v)
    except (TypeError, ValueError):
        return "-"
    if v == 0:
        return "-"
    return f"{v:,.2f}"


def _pct(v: float) -> str:
    if v is None:
        return "-"
    try:
        return f"{float(v):.2f}%"
    except Exception:
        return "-"


def _now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().strftime("%d-%b-%Y %H:%M IST")


