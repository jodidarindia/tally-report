"""
CA Corner — Bank & Investor Reports engine.

Generates two artefact families from live Tally/Busy data:

  1. CMA (Credit Monitoring Arrangement) — 5 RBI-format forms × 5 columns
     (2 historical audited FYs + 3 projected FYs). Bank submission ready.
       - Form II  : Operating Statement (P&L)
       - Form III : Analysis of Balance Sheet
       - Form IV  : Comparative Statement of Current Assets & Liabilities
       - Form V   : Maximum Permissible Bank Finance (MPBF)
       - Form VI  : Funds Flow Statement

  2. Investor Pitch Deck — 16-page PDF + 10-page teaser + 8-sheet XLSX,
     projected on the tenant's actual Tally revenue / GM / cash-flow.

Design contract:
  - Every output file carries the tenant's company name in a header on
    every page (`_add_header_footer` canvas hook) and the footer
    "Auto-generated by FLOWRA · <ISO timestamp> · Page X of Y".
  - The methodology page (last page of every PDF, last sheet of every
    XLSX) documents the exact derivation formula for each line item.
  - All monetary inputs are treated as INR lakhs (matches Krishna Sales
    reference CMA); the engine rounds to 2 decimals per RBI convention.
  - Pure functions — no DB imports; the route layer feeds already-scoped
    (tenant + company) data in, and takes bytes out.
"""
