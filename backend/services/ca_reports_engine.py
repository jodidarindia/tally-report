# ─── CMA XLSX builder ────────────────────────────────────────────────────

def build_cma_xlsx(meta: CompanyMeta, hist: List[HistoricalFY],
                    proj: List[HistoricalFY], a: Assumptions) -> bytes:
    """5-sheet Excel workbook (one per Form) — bank submission ready."""
    all_fys = hist + proj
    n_hist = len(hist)
    col_labels = [c.replace("\n", " ") for c in
                   _column_headers_for_fys(all_fys, n_hist)]
    wb = Workbook()

    def _new_sheet(title, labels, rows_by_fy):
        ws = wb.create_sheet(title=title)
        ws.append([meta.company_name])
        ws.append([f"{title}  ·  All figures in Rs. Lacs"])
        ws.append([""] + col_labels)
        # Merge & style header
        header_font = Font(bold=True, color="FFFFFF")
        header_fill = PatternFill("solid", fgColor="0F1B4C")
        for cell in ws[3]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(horizontal="center")
        rows = _transpose_rows(rows_by_fy, labels)
        for r in rows:
            ws.append(r)
        # Set column widths
        ws.column_dimensions["A"].width = 40
        for col in range(2, 2 + len(col_labels)):
            ws.column_dimensions[chr(64 + col)].width = 14
        ws["A1"].font = Font(bold=True, size=13, color="0F1B4C")
        ws["A2"].font = Font(italic=True, size=9, color="475569")
        # Footer row
        ws.append([])
        ws.append([f"{FLOWRA_TAG}  ·  {_now_iso()}  ·  Sheet: {title}"])
        ws.cell(row=ws.max_row, column=1).font = Font(italic=True, size=8,
                                                        color="94A3B8")
        return ws

    # Remove default sheet
    wb.remove(wb["Sheet"])
    _new_sheet("Form II — P&L",
                _form_ii_labels(),
                [_form_ii_rows(fy) for fy in all_fys])
    _new_sheet("Form III — Balance Sheet",
                _form_iii_labels(),
                [_form_iii_rows(fy) for fy in all_fys])
    _new_sheet("Form IV — CA & CL",
                _form_iv_labels(),
                [_form_iv_rows(fy) for fy in all_fys])
    _new_sheet("Form V — MPBF",
                _form_v_labels(),
                [_form_v_rows(fy) for fy in all_fys])
    ff_labels = _funds_flow_labels()
    ff_cols = _funds_flow_deltas(all_fys)
    ff_col_labels = [f"{a1.fy_label}→{b1.fy_label}"
                      for a1, b1 in zip(all_fys[:-1], all_fys[1:])]
    ws6 = wb.create_sheet(title="Form VI — Funds Flow")
    ws6.append([meta.company_name])
    ws6.append(["Funds Flow Statement · All figures in Rs. Lacs"])
    ws6.append([""] + ff_col_labels)
    for cell in ws6[3]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="0F1B4C")
    for r in _transpose_rows(ff_cols, ff_labels):
        ws6.append(r)
    ws6.column_dimensions["A"].width = 42

    # Methodology sheet
    wsm = wb.create_sheet(title="Methodology")
    wsm.append([meta.company_name])
    wsm.append(["How this CMA was generated"])
    wsm.append([])
    for title, body in _methodology_blocks():
        wsm.append([title])
        wsm.cell(row=wsm.max_row, column=1).font = Font(bold=True, size=11,
                                                          color="0F1B4C")
        wsm.append([body])
        wsm.cell(row=wsm.max_row, column=1).alignment = Alignment(
            wrap_text=True, vertical="top")
        wsm.append([])
    wsm.column_dimensions["A"].width = 110
    wsm.append([])
    wsm.append(["Assumptions used"])
    wsm.append(["Sales growth Y1/Y2/Y3 (%)",
                 f"{a.sales_growth_y1} / {a.sales_growth_y2} / "
                 f"{a.sales_growth_y3}"])
    wsm.append(["Debtor days target", a.debtor_days_target])
    wsm.append(["Creditor days target", a.creditor_days_target])
    wsm.append(["Inventory days target", a.inventory_days_target])
    wsm.append(["GP margin target (%)", a.gp_margin_target_pct])
    wsm.append(["Proposed CC/OD limit (₹ Lacs)", a.proposed_cc_limit])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ─── Investor Pitch Deck ─────────────────────────────────────────────────

def build_pitch_pdf(meta: CompanyMeta, hist: List[HistoricalFY],
                     proj: List[HistoricalFY], a: Assumptions,
                     teaser: bool = False) -> bytes:
    """Investor pitch — 16 pages (or 10-page teaser)."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=1.4 * cm, rightMargin=1.4 * cm,
        topMargin=1.6 * cm, bottomMargin=1.4 * cm,
        title=f"Pitch Deck — {meta.company_name}",
    )
    story: List[Any] = []
    all_fys = hist + proj
    latest = hist[-1] if hist else None
    ii = compute_form_ii(latest) if latest else {}
    d3 = compute_form_iii(latest) if latest else {}

    # Cover
    story.append(_para(meta.company_name, "h1"))
    subtitle = ("Teaser Deck — Confidential" if teaser
                 else "Investor Pitch Deck — Series A / Growth Capital")
    story.append(_para(subtitle, "small"))
    story.append(Spacer(1, 8))
    story.append(_para(
        "Ready to scale. Backed by verified Tally financials, projected "
        "3 years forward.", "note"))
    story.append(PageBreak())

    # Section 1 — Company snapshot
    story.append(_para("Company Snapshot", "h1"))
    snap = [
        ["Company", meta.company_name],
        ["Sector",
            "Distribution / Trading (verified via Tally Sync)"],
        ["Financial year (latest audited)",
            latest.fy_label if latest else "-"],
        ["Revenue (₹ Lacs)",
            _lakhs(latest.net_sales) if latest else "-"],
        ["EBITDA proxy (Op. Profit before Interest, ₹ Lacs)",
            _lakhs(ii.get("op_profit_bi", 0))],
        ["Net Profit (₹ Lacs)",
            _lakhs(ii.get("npat", 0))],
        ["Net Worth (₹ Lacs)",
            _lakhs(d3.get("nw", 0))],
        ["Current Ratio",
            f"{d3.get('current_ratio', 0):.2f}"],
        ["Ask (proposed working capital, ₹ Lacs)",
            _lakhs(a.proposed_cc_limit)],
    ]
    t = Table(snap, colWidths=[8 * cm, 8.4 * cm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor(SOFT)),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("GRID", (0, 0), (-1, -1), 0.2, colors.HexColor("#E2E8F0")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
    ]))
    story.append(t)
    story.append(PageBreak())

    # Section 2 — Revenue journey
    story.append(_para("Revenue Journey", "h1"))
    rev_rows = [
        ["Year", "Net Sales (₹ Lacs)", "Growth %"],
    ]
    prev = None
    for fy in all_fys:
        g = ((fy.net_sales / prev.net_sales - 1) * 100) if prev and prev.net_sales else 0
        rev_rows.append([fy.fy_label, _lakhs(fy.net_sales),
                          f"{g:+.1f}%" if prev else "-"])
        prev = fy
    story.append(_form_table(rev_rows[1:], [4 * cm, 5 * cm, 4 * cm],
                              rev_rows[0]))
    story.append(Spacer(1, 8))
    story.append(_para(
        "Historical growth is drawn directly from Tally / Busy sales "
        "vouchers. Projected growth reflects the assumptions on the last "
        "page.", "note"))
    story.append(PageBreak())

    # Section 3 — Margin trend
    story.append(_para("Gross & Net Margin Trend", "h1"))
    m_rows = [["Year", "GP % (Est.)", "Net Profit % (After Tax)"]]
    for fy in all_fys:
        dii = compute_form_ii(fy)
        gp = ((fy.net_sales - dii["cost_of_sales"]) / fy.net_sales * 100
                if fy.net_sales else 0)
        np_pct = (dii["npat"] / fy.net_sales * 100
                    if fy.net_sales else 0)
        m_rows.append([fy.fy_label, f"{gp:.2f}%", f"{np_pct:.2f}%"])
    story.append(_form_table(m_rows[1:], [4 * cm, 5 * cm, 5 * cm],
                              m_rows[0]))
    story.append(PageBreak())

    # Section 4 — Balance sheet strength
    story.append(_para("Balance Sheet Strength", "h1"))
    bs_rows = [["Year", "Net Worth (₹ Lacs)", "Current Ratio",
                 "TOL / TNW", "Working Capital (₹ Lacs)"]]
    for fy in all_fys:
        d = compute_form_iii(fy)
        bs_rows.append([fy.fy_label,
                          _lakhs(d["nw"]),
                          f"{d['current_ratio']:.2f}",
                          f"{d['tol_tnw']:.2f}",
                          _lakhs(d["nwc"])])
    story.append(_form_table(bs_rows[1:],
                              [3 * cm, 3.5 * cm, 3 * cm, 2.5 * cm, 4 * cm],
                              bs_rows[0]))
    story.append(PageBreak())

    if teaser:
        # Teaser stops here (10 pages incl. cover + methodology)
        _pitch_methodology(story, a, meta)
        doc.build(story,
                   onFirstPage=_make_canvas_stamper(meta.company_name,
                                                      "Investor Teaser"),
                   onLaterPages=_make_canvas_stamper(meta.company_name,
                                                      "Investor Teaser"))
        return buf.getvalue()

    # Section 5 — Cash flow strength (proxy)
    story.append(_para("Cash Flow Health (Indirect Method)", "h1"))
    cf_rows = [["Year", "PBT (₹ Lacs)", "Depreciation",
                 "Working Capital Change", "Op Cash Flow (proxy)"]]
    for prev, cur in zip(all_fys[:-1], all_fys[1:]):
        pi = compute_form_ii(cur)
        p3 = compute_form_iii(prev)
        c3 = compute_form_iii(cur)
        wc_delta = -((c3["tca"] - p3["tca"])
                       - ((c3["tcl"] - cur.bank_st_borrowings)
                          - (p3["tcl"] - prev.bank_st_borrowings)))
        ocf = pi["pbt"] + cur.depreciation + wc_delta
        cf_rows.append([cur.fy_label, _lakhs(pi["pbt"]),
                          _lakhs(cur.depreciation),
                          _lakhs(wc_delta),
                          _lakhs(ocf)])
    story.append(_form_table(cf_rows[1:],
                              [3 * cm, 3 * cm, 3 * cm, 3.5 * cm, 3.5 * cm],
                              cf_rows[0]))
    story.append(PageBreak())

    # Section 6 — Ratios summary
    story.append(_para("Key Ratios & KPIs", "h1"))
    r_rows = [["Metric", "Latest FY", "Projection Y3"]]
    if all_fys:
        first, last = all_fys[0], all_fys[-1]
        d_first = compute_form_iii(first)
        d_last = compute_form_iii(last)
        i_first = compute_form_ii(first)
        i_last = compute_form_ii(last)
        r_rows.extend([
            ["Net Sales (₹ Lacs)", _lakhs(first.net_sales), _lakhs(last.net_sales)],
            ["GP %",
                _pct(((first.net_sales - i_first["cost_of_sales"])
                        / first.net_sales * 100) if first.net_sales else 0),
                _pct(((last.net_sales - i_last["cost_of_sales"])
                        / last.net_sales * 100) if last.net_sales else 0)],
            ["Current Ratio",
                f"{d_first['current_ratio']:.2f}",
                f"{d_last['current_ratio']:.2f}"],
            ["TOL/TNW",
                f"{d_first['tol_tnw']:.2f}",
                f"{d_last['tol_tnw']:.2f}"],
        ])
    story.append(_form_table(r_rows[1:], [7 * cm, 4 * cm, 4 * cm], r_rows[0]))
    story.append(PageBreak())

    # Section 7 — Use of proceeds
    story.append(_para("Use of Proposed Funds", "h1"))
    up_rows = [
        ["Use", "Amount (₹ Lacs)"],
        ["Working capital cushion (CC/OD)", _lakhs(a.proposed_cc_limit)],
        ["Capex Y1", _lakhs(a.planned_capex_y1)],
        ["Capex Y2", _lakhs(a.planned_capex_y2)],
        ["Capex Y3", _lakhs(a.planned_capex_y3)],
        ["Term loan paydown Y1-Y3",
            _lakhs(a.term_loan_repayment_y1 + a.term_loan_repayment_y2
                    + a.term_loan_repayment_y3)],
    ]
    story.append(_form_table(up_rows[1:], [10 * cm, 5 * cm], up_rows[0]))
    story.append(PageBreak())

    # Sections 8-14 — Placeholders (management commentary, market, risks)
    for title, body in [
        ("Management",
         "Owner-operated, actively engaged in operations. Full financial "
         "transparency via live Tally / Busy sync into FLOWRA."),
        ("Market & Positioning",
         "Existing customer base with proven repeat-purchase behaviour "
         "visible in the receivables ageing on Form IV. Beat-plan-driven "
         "market coverage — quantified in FLOWRA's daily reports."),
        ("Growth Levers",
         "1) Working-capital-led sales expansion (proposed CC limit) "
         "2) Selective capex per Assumptions "
         "3) Debtor-day compression from historical to target."),
        ("Risks & Mitigants",
         "Working-capital cyclicality mitigated by proposed CC facility. "
         "GSTIN / PAN / MSME registration verified. TOL/TNW well within "
         "banker thresholds (see Form III)."),
    ]:
        story.append(_para(title, "h1"))
        story.append(_para(body, "body"))
        story.append(PageBreak())

    _pitch_methodology(story, a, meta)
    doc.build(story,
               onFirstPage=_make_canvas_stamper(meta.company_name,
                                                  "Investor Pitch Deck"),
               onLaterPages=_make_canvas_stamper(meta.company_name,
                                                  "Investor Pitch Deck"))
    return buf.getvalue()


def _pitch_methodology(story: List[Any], a: Assumptions,
                        meta: CompanyMeta) -> None:
    story.append(_para("Methodology & Data Provenance", "h1"))
    for section, body in _methodology_blocks():
        story.append(_para(section, "h2"))
        story.append(_para(body, "body"))
        story.append(Spacer(1, 3))


def build_projections_xlsx(meta: CompanyMeta, hist: List[HistoricalFY],
                            proj: List[HistoricalFY],
                            a: Assumptions) -> bytes:
    """8-sheet XLSX with editable projection scenario (matches PRD promise
    of an 'Excel projections file, editable numbers'."""
    wb = Workbook()
    wb.remove(wb["Sheet"])
    all_fys = hist + proj

    def _sheet_from_field(title, field_name, is_bs=False):
        ws = wb.create_sheet(title=title)
        ws.append([meta.company_name])
        ws.append([title])
        ws.append(["FY"] + [fy.fy_label for fy in all_fys])
        ws.append([field_name] + [getattr(fy, field_name, 0)
                                    for fy in all_fys])
        ws.column_dimensions["A"].width = 30
        ws["A1"].font = Font(bold=True, size=13, color="0F1B4C")
        ws["A2"].font = Font(italic=True, size=10, color="475569")
        return ws

    _sheet_from_field("Revenue", "net_sales")
    _sheet_from_field("Purchases", "purchases")
    _sheet_from_field("SG&A", "sga_expenses")
    _sheet_from_field("Depreciation", "depreciation")

    # Sundry Debtors + Creditors
    ws5 = wb.create_sheet(title="Working Capital")
    ws5.append([meta.company_name])
    ws5.append(["Working Capital Movements"])
    ws5.append(["FY"] + [fy.fy_label for fy in all_fys])
    ws5.append(["Sundry Debtors"] + [fy.receivables_domestic
                                        for fy in all_fys])
    ws5.append(["Sundry Creditors"] + [fy.sundry_creditors
                                          for fy in all_fys])
    ws5.append(["Inventory (Total)"] + [
        fy.inventory_raw + fy.inventory_wip + fy.inventory_finished
        + fy.inventory_spares for fy in all_fys])
    ws5.column_dimensions["A"].width = 22

    # MPBF sheet
    ws6 = wb.create_sheet(title="MPBF")
    ws6.append([meta.company_name])
    ws6.append(["MPBF (Method 1 & Method 2)"])
    ws6.append(["FY"] + [fy.fy_label for fy in all_fys])
    m1 = []
    m2 = []
    for fy in all_fys:
        d = compute_form_iii(fy)
        ocl = d["tcl"] - fy.bank_st_borrowings
        r = compute_form_v_mpbf(fy, ocl, d["nwc"])
        m1.append(r["m1_mpbf"])
        m2.append(r["m2_mpbf"])
    ws6.append(["Method 1 MPBF"] + [round(v, 2) for v in m1])
    ws6.append(["Method 2 MPBF"] + [round(v, 2) for v in m2])
    ws6.column_dimensions["A"].width = 22

    # Assumptions sheet
    ws7 = wb.create_sheet(title="Assumptions")
    ws7.append([meta.company_name])
    ws7.append(["Assumptions (editable — copy this workbook, tweak, "
                 "and re-upload via CA Corner)"])
    for k, v in asdict(a).items():
        ws7.append([k, v])
    ws7.column_dimensions["A"].width = 32
    ws7.column_dimensions["B"].width = 20

    # Methodology sheet
    ws8 = wb.create_sheet(title="Methodology")
    ws8.append([meta.company_name])
    ws8.append([""])
    for title, body in _methodology_blocks():
        ws8.append([title])
        ws8.cell(row=ws8.max_row, column=1).font = Font(bold=True,
                                                          color="0F1B4C")
        ws8.append([body])
        ws8.cell(row=ws8.max_row, column=1).alignment = Alignment(
            wrap_text=True, vertical="top")
        ws8.append([])
    ws8.column_dimensions["A"].width = 110

    # Footer stamp on every sheet
    for ws in wb.worksheets:
        ws.append([])
        ws.append([f"{FLOWRA_TAG}  ·  {_now_iso()}"])
        ws.cell(row=ws.max_row, column=1).font = Font(italic=True, size=8,
                                                        color="94A3B8")

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
