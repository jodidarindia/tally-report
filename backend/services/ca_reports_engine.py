# ─── Projection engine ───────────────────────────────────────────────────

def project_future_fys(hist: List[HistoricalFY], a: Assumptions,
                        n_future: int = 3) -> List[HistoricalFY]:
    """Take the last historical FY and generate n_future projected FYs
    using the user assumptions + historical ratios where the user did not
    override them.

    Formulas (documented on the methodology page of each output):
      Net Sales_{y+n}  = Net Sales_y × ∏(1 + growth_i%)
      Gross Sales_{y+n} = Net Sales_{y+n} × (Gross/Net)_hist_avg
      Purchases_{y+n}  = Net Sales_{y+n} × (Purchases/Net Sales)_hist_avg
                          — reduced pro-rata to hit gp_margin_target_pct
      Sundry Debtors   = Net Sales × debtor_days_target / 365
      Sundry Creditors = Purchases × creditor_days_target / 365
      Inventory FG     = Cost of Sales × inventory_days_target / 365
      Term Loans       = prior_TL − term_loan_repayment_i
      Gross Block      = prior_GB + planned_capex_i
      Reserves         = prior_reserves + Net Profit_i − withdrawals_i
      Bank ST borrow.  = ANCHOR to Actual MPBF result of Form V (feedback
                          from the Form V computation, capped at proposed
                          CC limit if user specified).
    """
    if not hist:
        return []
    last = hist[-1]
    hist_ratios = _fit_ratios(hist)
    growths = [a.sales_growth_y1, a.sales_growth_y2, a.sales_growth_y3]
    capex = [a.planned_capex_y1, a.planned_capex_y2, a.planned_capex_y3]
    tl_paydown = [a.term_loan_repayment_y1, a.term_loan_repayment_y2,
                   a.term_loan_repayment_y3]
    out: List[HistoricalFY] = []
    prior = last
    for i in range(min(n_future, 3)):
        g = growths[i] / 100.0
        fy_label = _next_fy(prior.fy_label)
        ns = round(prior.net_sales * (1 + g), 2)
        gs_ratio = hist_ratios["gross_over_net"]
        gs = round(ns * gs_ratio, 2)

        # Cost side — target GP margin overrides historical ratio if user set it
        gp = a.gp_margin_target_pct / 100.0
        cogs_target = ns * (1 - gp)
        pur_ratio = hist_ratios["pur_over_cogs"]
        wages_ratio = hist_ratios["wages_over_cogs"]
        power_ratio = hist_ratios["power_over_cogs"]
        dexp_ratio = hist_ratios["dexp_over_cogs"]
        dep_ratio = hist_ratios["dep_over_ns"]
        sga_ratio = hist_ratios["sga_over_ns"]
        int_ratio = hist_ratios["int_over_ns"]

        purchases = round(cogs_target * pur_ratio, 2)
        wages = round(cogs_target * wages_ratio, 2)
        power = round(cogs_target * power_ratio, 2)
        dexp = round(cogs_target * dexp_ratio, 2)
        dep = round(ns * dep_ratio, 2)
        sga = round(ns * sga_ratio, 2)
        interest = round(ns * int_ratio, 2)

        opening_fg = prior.closing_stock_fg
        cost_of_sales = purchases + wages + power + dexp + dep + opening_fg
        # target FG inventory in days
        closing_fg = round((cost_of_sales * a.inventory_days_target / 365), 2)
        cost_of_sales_net = cost_of_sales - closing_fg

        pbt = ns - cost_of_sales_net - sga - interest
        tax = round(max(pbt, 0) * 0.25, 2)   # heuristic 25% tax; user can override
        np_after_tax = pbt - tax

        # Balance sheet projections
        debtors_d = round(ns * a.debtor_days_target / 365, 2)
        creditors_c = round(purchases * a.creditor_days_target / 365, 2)
        inv_raw = round(purchases * a.inventory_days_target / 365 * 0.5, 2)
        inv_wip = round(cost_of_sales_net * a.inventory_days_target / 365
                         * 0.2, 2)
        inv_fg = closing_fg
        inv_spares = prior.inventory_spares

        term_loans = max(prior.term_loans - tl_paydown[i], 0)
        gross_block = prior.gross_block + capex[i]
        accum_dep = prior.accumulated_depreciation + dep
        reserves = prior.reserves_surplus + np_after_tax - prior.withdrawals

        # Bank ST borrowing capped at proposed CC limit (if any)
        proj_bank = (a.proposed_cc_limit
                     if a.proposed_cc_limit > 0
                     else prior.bank_st_borrowings)

        out.append(HistoricalFY(
            fy_label=fy_label,
            gross_sales=gs,
            other_direct_income=prior.other_direct_income * (1 + g),
            net_sales=ns,
            purchases=purchases,
            direct_wages=wages,
            power_fuel=power,
            other_direct_exp=dexp,
            depreciation=dep,
            opening_stock_fg=opening_fg,
            closing_stock_fg=closing_fg,
            sga_expenses=sga,
            interest=interest,
            other_non_op_income=prior.other_non_op_income,
            other_non_op_expense=prior.other_non_op_expense,
            provision_for_tax=tax,
            bank_st_borrowings=proj_bank,
            other_st_borrowings=prior.other_st_borrowings,
            sundry_creditors=creditors_c,
            advances_from_customers=prior.advances_from_customers,
            other_statutory_liab=prior.other_statutory_liab,
            tl_current_portion=min(term_loans, tl_paydown[i] * 1.0),
            other_current_liab=prior.other_current_liab,
            term_loans=term_loans,
            unsecured_loans=prior.unsecured_loans,
            other_term_liab=prior.other_term_liab,
            proprietors_capital=prior.proprietors_capital,
            reserves_surplus=reserves,
            withdrawals=prior.withdrawals,
            cash_bank_balance=prior.cash_bank_balance,
            investments_current=prior.investments_current,
            receivables_domestic=debtors_d,
            receivables_export=prior.receivables_export,
            inventory_raw=inv_raw,
            inventory_wip=inv_wip,
            inventory_finished=inv_fg,
            inventory_spares=inv_spares,
            advances_to_suppliers=prior.advances_to_suppliers,
            advance_tax=prior.advance_tax,
            other_current_assets=prior.other_current_assets,
            gross_block=gross_block,
            accumulated_depreciation=accum_dep,
            other_non_current_assets=prior.other_non_current_assets,
            intangibles=prior.intangibles,
        ))
        prior = out[-1]
    return out


def _fit_ratios(hist: List[HistoricalFY]) -> Dict[str, float]:
    """Compute average historical ratios used as projection defaults."""
    def _safe_avg(nums, dens):
        pairs = [(n, d) for n, d in zip(nums, dens) if d and d != 0]
        if not pairs:
            return 0.0
        return sum(n / d for n, d in pairs) / len(pairs)
    ns = [h.net_sales for h in hist]
    gs = [h.gross_sales for h in hist]
    cogs = [h.purchases + h.direct_wages + h.power_fuel + h.other_direct_exp
             for h in hist]
    return {
        "gross_over_net":  _safe_avg(gs, ns) or 1.0,
        "pur_over_cogs":   _safe_avg([h.purchases for h in hist], cogs) or 0.8,
        "wages_over_cogs": _safe_avg([h.direct_wages for h in hist], cogs) or 0.05,
        "power_over_cogs": _safe_avg([h.power_fuel for h in hist], cogs) or 0.02,
        "dexp_over_cogs":  _safe_avg([h.other_direct_exp for h in hist], cogs) or 0.03,
        "dep_over_ns":     _safe_avg([h.depreciation for h in hist], ns) or 0.01,
        "sga_over_ns":     _safe_avg([h.sga_expenses for h in hist], ns) or 0.05,
        "int_over_ns":     _safe_avg([h.interest for h in hist], ns) or 0.01,
    }


def _next_fy(label: str) -> str:
    """'2023-24' → '2024-25'."""
    try:
        a, b = label.split("-")
        na = int(a) + 1
        nb = str(int(b) + 1).zfill(2)
        return f"{na}-{nb}"
    except Exception:
        return "Next FY"


# ─── Derived aggregates the forms need ───────────────────────────────────

def compute_form_ii(fy: HistoricalFY) -> Dict[str, float]:
    """Form II — Operating Statement derived totals."""
    cost_of_prod = (fy.purchases + fy.direct_wages + fy.power_fuel
                     + fy.other_direct_exp + fy.depreciation)
    cost_of_sales = cost_of_prod + fy.opening_stock_fg - fy.closing_stock_fg
    total_cost = cost_of_sales + fy.sga_expenses
    op_profit_bi = fy.net_sales - total_cost
    op_profit_ai = op_profit_bi - fy.interest
    non_op_net = fy.other_non_op_income - fy.other_non_op_expense
    pbt = op_profit_ai + non_op_net
    npat = pbt - fy.provision_for_tax
    return {
        "cost_of_production": cost_of_prod,
        "cost_of_sales": cost_of_sales,
        "total_cost": total_cost,
        "op_profit_bi": op_profit_bi,
        "op_profit_ai": op_profit_ai,
        "non_op_net": non_op_net,
        "pbt": pbt,
        "npat": npat,
    }


def compute_form_iii(fy: HistoricalFY) -> Dict[str, float]:
    """Form III — Balance Sheet Analysis derived totals + ratios."""
    tcl = (fy.bank_st_borrowings + fy.other_st_borrowings + fy.sundry_creditors
            + fy.advances_from_customers + fy.other_statutory_liab
            + fy.tl_current_portion + fy.other_current_liab)
    ttl = fy.term_loans + fy.unsecured_loans + fy.other_term_liab
    tol = tcl + ttl
    nw = (fy.proprietors_capital + fy.reserves_surplus - fy.withdrawals)
    tnw = nw - fy.intangibles
    tca = (fy.cash_bank_balance + fy.investments_current
            + fy.receivables_domestic + fy.receivables_export
            + fy.inventory_raw + fy.inventory_wip + fy.inventory_finished
            + fy.inventory_spares + fy.advances_to_suppliers
            + fy.advance_tax + fy.other_current_assets)
    net_block = fy.gross_block - fy.accumulated_depreciation
    total_assets = (tca + net_block + fy.other_non_current_assets
                     + fy.intangibles)
    nwc = tca - tcl
    current_ratio = (tca / tcl) if tcl > 0 else 0
    tol_tnw = (tol / tnw) if tnw > 0 else 0
    ttl_tnw = (ttl / tnw) if tnw > 0 else 0
    return {
        "tcl": tcl, "ttl": ttl, "tol": tol, "nw": nw, "tnw": tnw,
        "tca": tca, "net_block": net_block, "total_assets": total_assets,
        "nwc": nwc, "current_ratio": current_ratio,
        "tol_tnw": tol_tnw, "ttl_tnw": ttl_tnw,
    }


def compute_form_v_mpbf(fy: HistoricalFY, other_cl_excl_bank: float,
                         projected_nwc: float) -> Dict[str, float]:
    """Form V — Maximum Permissible Bank Finance (both methods)."""
    d3 = compute_form_iii(fy)
    tca = d3["tca"]
    ocl = other_cl_excl_bank
    wcg = tca - ocl
    # Method 1: min NWC = 25% of WCG
    m1_min_nwc = 0.25 * wcg
    m1_a = wcg - m1_min_nwc
    m1_b = wcg - projected_nwc
    m1_mpbf = min(m1_a, m1_b)
    m1_shortfall = max(m1_min_nwc - projected_nwc, 0)
    # Method 2: min NWC = 25% of TCA
    m2_min_nwc = 0.25 * tca
    m2_a = wcg - m2_min_nwc
    m2_b = wcg - projected_nwc
    m2_mpbf = min(m2_a, m2_b)
    m2_shortfall = max(m2_min_nwc - projected_nwc, 0)
    return {
        "tca": tca, "ocl": ocl, "wcg": wcg,
        "m1_min_nwc": m1_min_nwc, "m1_a": m1_a, "m1_b": m1_b,
        "m1_mpbf": max(m1_mpbf, 0), "m1_shortfall": m1_shortfall,
        "m2_min_nwc": m2_min_nwc, "m2_a": m2_a, "m2_b": m2_b,
        "m2_mpbf": max(m2_mpbf, 0), "m2_shortfall": m2_shortfall,
    }


# ─── PDF generation utilities ────────────────────────────────────────────

def _make_canvas_stamper(company_name: str, doc_title: str):
    """Returns an on-page callback that stamps company name (header) and
    'Auto-generated by FLOWRA · timestamp · Page X of Y' (footer) on every
    page — user's mandatory branding requirement."""
    ts = _now_iso()

    def _on_page(canvas, doc):
        canvas.saveState()
        w, h = A4 if doc.pagesize == A4 else doc.pagesize
        # Header
        canvas.setFillColor(colors.HexColor(BRAND))
        canvas.setFont("Helvetica-Bold", 10)
        canvas.drawString(1.2 * cm, h - 0.9 * cm, company_name)
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#64748B"))
        canvas.drawRightString(w - 1.2 * cm, h - 0.9 * cm, doc_title)
        canvas.setStrokeColor(colors.HexColor("#E2E8F0"))
        canvas.line(1.2 * cm, h - 1.1 * cm, w - 1.2 * cm, h - 1.1 * cm)
        # Footer
        canvas.setFont("Helvetica-Oblique", 7)
        canvas.setFillColor(colors.HexColor("#94A3B8"))
        footer = f"{FLOWRA_TAG}  ·  {ts}  ·  Page {doc.page}"
        canvas.drawString(1.2 * cm, 0.7 * cm, footer)
        canvas.setFillColor(colors.HexColor(ACCENT))
        canvas.setFont("Helvetica-Bold", 7)
        canvas.drawRightString(w - 1.2 * cm, 0.7 * cm, "flowralive.in")
        canvas.restoreState()
    return _on_page


def _para(text: str, style: str = "body") -> Paragraph:
    styles = getSampleStyleSheet()
    if style == "h1":
        p = ParagraphStyle("h1", parent=styles["Title"], fontSize=16,
                            textColor=colors.HexColor(BRAND),
                            spaceAfter=6)
    elif style == "h2":
        p = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=11,
                            textColor=colors.HexColor(BRAND),
                            spaceBefore=8, spaceAfter=4)
    elif style == "small":
        p = ParagraphStyle("small", parent=styles["BodyText"], fontSize=7,
                            textColor=colors.HexColor("#64748B"),
                            leading=9)
    elif style == "note":
        p = ParagraphStyle("note", parent=styles["BodyText"], fontSize=8,
                            textColor=colors.HexColor("#475569"),
                            leading=11, italic=True)
    else:
        p = ParagraphStyle("body", parent=styles["BodyText"], fontSize=9,
                            leading=12)
    return Paragraph(text, p)


def _form_table(rows: List[List[Any]], col_widths: List[float],
                 headers: List[str], highlight_rows: Optional[List[int]] = None
                 ) -> Table:
    highlight_rows = highlight_rows or []
    # Guard: clamp indices to the actual body length so out-of-range hints
    # (which can happen if a form has fewer rows in a particular tenant)
    # don't crash ReportLab's row-background painter.
    n_body = len(rows)
    highlight_rows = [r for r in highlight_rows if 0 <= r < n_body]
    data = [headers] + rows
    t = Table(data, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(BRAND)),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 8),
        ("FONTSIZE", (0, 1), (-1, -1), 8),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("TOPPADDING", (0, 0), (-1, 0), 6),
        ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.HexColor(BRAND)),
        ("GRID", (0, 1), (-1, -1), 0.15, colors.HexColor("#E2E8F0")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
            [colors.white, colors.HexColor(SOFT)]),
    ]
    for r in highlight_rows:
        style.append(("BACKGROUND", (0, r + 1), (-1, r + 1),
                      colors.HexColor("#DBEAFE")))
        style.append(("FONTNAME", (0, r + 1), (-1, r + 1), "Helvetica-Bold"))
    t.setStyle(TableStyle(style))
    return t


def _column_headers_for_fys(all_fys: List[HistoricalFY], n_hist: int
                              ) -> List[str]:
    """Match the bank CMA convention: '2021-22 Actual (1)',
    '2023-24 Estimated (3)', '2024-25 Projections (4)'."""
    labels = []
    for i, fy in enumerate(all_fys):
        if i < n_hist - 1:
            tag = "Actual"
        elif i == n_hist - 1:
            tag = "Estimated"
        else:
            tag = "Projections"
        labels.append(f"{fy.fy_label}\n{tag} ({i + 1})")
    return labels


# ─── CMA PDF builder ─────────────────────────────────────────────────────

def build_cma_pdf(meta: CompanyMeta, hist: List[HistoricalFY],
                   proj: List[HistoricalFY], a: Assumptions) -> bytes:
    """Generate the 5-form CMA report as a PDF."""
    all_fys = hist + proj
    n_hist = len(hist)
    col_labels = _column_headers_for_fys(all_fys, n_hist)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=1.2 * cm, rightMargin=1.2 * cm,
        topMargin=1.6 * cm, bottomMargin=1.2 * cm,
        title=f"CMA — {meta.company_name}",
    )
    story: List[Any] = []

    # ── Cover page ──
    story.append(_para(
        f"CMA Report — {meta.company_name}", "h1"))
    story.append(_para(
        f"Credit Monitoring Arrangement · Prepared for: {meta.prepared_for}",
        "small"))
    story.append(Spacer(1, 8))
