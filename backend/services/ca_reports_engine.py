def _funds_flow_deltas(all_fys: List[HistoricalFY]) -> List[List[str]]:
    """Compute funds-flow movement between consecutive FYs."""
    out = []
    for prev, cur in zip(all_fys[:-1], all_fys[1:]):
        pi = compute_form_ii(cur)
        p3 = compute_form_iii(prev)
        c3 = compute_form_iii(cur)
        pbt = pi["pbt"]
        dep = cur.depreciation
        d_cap = max(cur.proprietors_capital - prev.proprietors_capital, 0)
        d_tl = max((cur.term_loans + cur.unsecured_loans + cur.other_term_liab)
                    - (prev.term_loans + prev.unsecured_loans
                        + prev.other_term_liab), 0)
        d_fa_dec = max(prev.gross_block - cur.gross_block, 0)
        d_nca_dec = max(prev.other_non_current_assets
                          - cur.other_non_current_assets, 0)
        total_sources = pbt + dep + d_cap + d_tl + d_fa_dec + d_nca_dec

        net_loss = max(-pi["npat"], 0)
        dec_tl = max((prev.term_loans + prev.unsecured_loans
                       + prev.other_term_liab)
                       - (cur.term_loans + cur.unsecured_loans
                           + cur.other_term_liab), 0)
        d_fa_inc = max(cur.gross_block - prev.gross_block, 0)
        d_nca_inc = max(cur.other_non_current_assets
                          - prev.other_non_current_assets, 0)
        div_wd = cur.withdrawals
        total_uses = net_loss + dec_tl + d_fa_inc + d_nca_inc + div_wd

        lt_surplus = total_sources - total_uses
        d_ca = c3["tca"] - p3["tca"]
        d_cl_ex_bank = ((c3["tcl"] - cur.bank_st_borrowings)
                          - (p3["tcl"] - prev.bank_st_borrowings))
        d_wcg = d_ca - d_cl_ex_bank
        net_sd = lt_surplus - d_wcg
        d_bank = cur.bank_st_borrowings - prev.bank_st_borrowings

        row_dict = {
            "SOURCES": "",
            "  a) Net Profit (before tax)": _lakhs(pbt),
            "  b) Depreciation": _lakhs(dep),
            "  c) Increase in Capital": _lakhs(d_cap),
            "  d) Increase in Term Liabilities": _lakhs(d_tl),
            "  e) Decrease in Fixed Assets": _lakhs(d_fa_dec),
            "  f) Decrease in Other Non-current Assets": _lakhs(d_nca_dec),
            "TOTAL SOURCES": _lakhs(total_sources),
            "USES": "",
            "  a) Net Loss": _lakhs(net_loss),
            "  b) Decrease in Term Liabilities": _lakhs(dec_tl),
            "  c) Increase in Fixed Assets": _lakhs(d_fa_inc),
            "  d) Increase in Other Non-current Assets": _lakhs(d_nca_inc),
            "  e) Dividend / Withdrawals": _lakhs(div_wd),
            "TOTAL USES": _lakhs(total_uses),
            "Long-term Surplus / (Deficit)": _lakhs(lt_surplus),
            "Δ Current Assets": _lakhs(d_ca),
            "Δ Current Liab. (excl. bank borrowings)": _lakhs(d_cl_ex_bank),
            "Δ Working Capital Gap": _lakhs(d_wcg),
            "Net Surplus / (Deficit)": _lakhs(net_sd),
            "Δ Bank Borrowings (residual)": _lakhs(d_bank),
        }
        out.append([row_dict.get(k, "-") for k in _FF_LABELS])
    return out


def _transpose_rows(cols: List[List[Any]], labels: List[str]) -> List[List[Any]]:
    """Convert [column1_values, column2_values, ...] into rows where each
    row is [label, col1_val, col2_val, ...]. Assumes all columns are the
    same length as `labels`."""
    rows = []
    for i, label in enumerate(labels):
        row = [label]
        for col in cols:
            row.append(col[i] if i < len(col) else "-")
        rows.append(row)
    return rows


