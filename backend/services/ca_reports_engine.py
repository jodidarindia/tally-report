def _months(part: float, base: float) -> str:
    """part / base * 12 → 'X.Xm'. Returns '-' when base is zero."""
    if not base or base <= 0:
        return "-"
    m = part * 12 / base
    if m == 0:
        return "-"
    return f"{m:.1f}m"


